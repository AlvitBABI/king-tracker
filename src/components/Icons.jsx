export function Stars({ value, size = 12 }) {
  if (!value) return null
  return (
    <span className="stars-inline" aria-label={`${value} out of 5 stars`}>
      {[1, 2, 3, 4, 5].map((n) => (
        <Star key={n} filled={n <= value} width={size} height={size} />
      ))}
    </span>
  )
}
